VMAP = [0, 1, 1, 2, 3, 4, 5, 5, 6, 7, 8]      # 太い字の段 → 細い字の段(大文字 7 → 9 段)
BOLD_FIX = {                                    # 手で描いた太い字
    'M': ['##....##', '###..###', '########', '##.##.##', '##.##.##', '##....##', '##....##', '##....##', '##....##'],
    'W': ['##....##', '##....##', '##....##', '##....##', '##.##.##', '##.##.##', '########', '###..###', '##....##'],
    'w': ['........'] * 3 + ['##....##', '##....##', '##.##.##', '##.##.##', '########', '.##..##.'],
    'N': ['##...##', '###..##', '###..##', '####.##', '##.####', '##..###', '##..###', '##...##', '##...##'],
}


def bold(ch):
    """太い字(ROWS 段、どの段も同じ幅の文字列)"""
    if ch in BOLD_FIX:
        r = BOLD_FIX[ch]
        w = max(len(x) for x in r)
    else:
        src = G[ch] + [''] * 9
        w = max(len(x) for x in G[ch])
        r = [src[k].ljust(w, '.') for k in VMAP]
        # 1 ドットの隙間は太らせると埋まるので、先に 2 ドットに広げる
        gaps = [x for x in range(1, w - 1) if any(t[x - 1] == '#' and t[x] == '.' and t[x + 1] == '#' for t in r)]
        r = [''.join(c * (2 if i in gaps else 1) for i, c in enumerate(t)) for t in r]
        r = [''.join('#' if t[x] == '#' or (x and t[x - 1] == '#') else '.' for x in range(len(t))) + t[-1] for t in r]
        w = len(r[0])
    if w > 8:
        raise SystemExit('gen_font: 太い字 %r の幅が 8 ドットを超える' % ch)
    return [x.ljust(w, '.') for x in r] + ['.' * w] * (ROWS - len(r))


def width(ch):
    return len(bold(ch)[0])


def advance(s):
    """字の送りの合計(ドット)"""
    for ch in s:
        if ch not in G:
            raise SystemExit('gen_font: 字幕の字体に無い字 %r (%r)' % (ch, s))
    return sum(width(ch) + 1 for ch in s) - (1 if s else 0)


def font_bytes():
    out = bytearray(ROWS * 96 + 96)
    for ch in G:
        k = ord(ch) - 0x20
        for r, row in enumerate(bold(ch)):
            b = 0
            for i, p in enumerate(row):
                if p == '#':
                    b |= 0x80 >> i
            out[r * 96 + k] = b
        out[ROWS * 96 + k] = width(ch) + 1
    return bytes(out)


def wrap(text, first):
    """1 行目は名前の札の幅 first だけ狭い。言葉の切れ目で折る"""
    lines, cur = [], ''
    for w in text.split(' '):
        t = (cur + ' ' + w) if cur else w
        room = SCREEN_W - 2 * MARGIN - (first if not lines else 0)
        if cur and advance(t) > room:
            lines.append(cur)
            cur = w
        else:
            cur = t
    lines.append(cur)
    if len(lines) > 3:
        raise SystemExit('gen_font: 字幕が 3 行に収まらない: %r' % text)
    return lines


def layout(text, who):
    """字幕の文字列(バイト列)。名前の札と 1 行目をつなげて真ん中に置き、2 行目からも 1 行ずつ真ん中に"""
    if not text:
        return b''
    tag = TAGS[who] or ''
    tw = advance(tag) + (1 if tag else 0)
    lines = wrap(text, tw)
    y = BAND_MID - (len(lines) * LINE_H - (LINE_H - ROWS)) // 2
    out = bytearray()
    for i, ln in enumerate(lines):
        w = advance(ln) + (tw if i == 0 else 0)
        x = max(2, (SCREEN_W - w) // 2)
        if i == 0:
            out += bytes((x, y))
            x += tw
        else:
            out.append(0x1F)
        out.append(x)
        out += ln.encode('ascii')
    return bytes(out)


def c_str(b):
    """C の文字列の書き方に(制御の字は 3 桁の 8 進で)"""
    s = ''
    for v in b:
        ch = chr(v)
        s += ch if 0x20 <= v < 0x7F and ch not in '"\\?' else '\\%03o' % v
    return '"' + s + '"'


def render(px, b, who, col):
    """film_say と同じ手順で描く(見本の絵用)。px[y][x] へ色番号"""
    if not b:
        return
    y = b[1]
    ital = who in (0, 2)
    tag = TAGS[who]
    def line(s, x0, y):
        for r in range(ROWS):
            x = x0 + (ITAL[r] if ital and s is not tag else 0)
            for ch in s:
                k = ord(ch) - 0x20
                fb = FB[r * 96 + k]
                for i in range(FB[ROWS * 96 + k]):
                    if fb & (0x80 >> i):
                        px[y + r][x] = col
                    x += 1
    if tag:
        line(tag, b[0], y)
    i = 2
    while True:
        x = b[i]
        j = i + 1
        while j < len(b) and b[j] != 0x1F:
            j += 1
        line(b[i + 1:j].decode(), x, y)
        if j >= len(b):
            break
        i = j + 1
        y += LINE_H


FB = font_bytes()


def preview(out):
    from PIL import Image
    PALC = {1: (0, 0, 0), 2: (255, 255, 255), 3: (255, 36, 36), 4: (255, 146, 36), 5: (36, 219, 73), 6: (109, 219, 255)}
    COL = [6, 2, 4, 4, 5, 3]
    samples = [(0, 'The town fell at dawn.'), (1, "Let's go."), (2, 'Papa, hurry!'), (4, 'Bandits! On your tail!'),
               (3, 'I knew you would come!'), (5, 'You will never catch us!'),
               (0, 'You have 6 hours to save her. They put her in a rocket bound for space.')]
    bands = []
    for who, t in samples:
        px = [[1] * SCREEN_W for _ in range(52)]
        render(px, layout(t, who), who, COL[who])
        bands.append(px)
    im = Image.new('RGB', (SCREEN_W, 54 * len(bands)), (40, 40, 40))
    q = im.load()
    for n, px in enumerate(bands):
        for y in range(52):
            for x in range(SCREEN_W):
                q[x, n * 54 + y] = PALC[px[y][x]]
    im = im.resize((SCREEN_W * 3, im.height * 3), Image.NEAREST)
    im.save(out)


