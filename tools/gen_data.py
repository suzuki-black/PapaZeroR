def shrink(rows, k, ch):
    """絵の ch の画素を k 倍に縮め、足もと(下の真ん中)をそろえる。担がれたヒナは誘拐犯と同じ割合で縮むよう、16 行全体を縮める。
    縮めた先の 1 画素には、元の範囲でいちばん多い文字(空白を含む)を置く(2 枚の色が同じ画素に重ならない)"""
    out = [['.'] * 16 for _ in range(16)]
    n = 16
    m = max(1, round(n * k))
    for y in range(m):
        for x in range(m):
            sy0, sy1 = int(y * n / m), max(int(y * n / m) + 1, int((y + 1) * n / m))
            sx0, sx1 = int(x * n / m), max(int(x * n / m) + 1, int((x + 1) * n / m))
            cells = [rows[yy][xx] for yy in range(sy0, sy1) for xx in range(sx0, sx1)]
            filled = [c for c in cells if c != '.']
            if len(filled) * 2 >= len(cells):
                best = max(set(filled), key=filled.count)
                if best == ch:
                    out[16 - m + y][(16 - m) // 2 + x] = '#'
    return [''.join(r) for r in out]


